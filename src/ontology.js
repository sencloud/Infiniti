// ============================================================
// 本体（Ontology）定义：图谱的"世界观"
// ============================================================
// 【v4 泛化】人物只是系统的"接入点"之一，系统本质是通用知识图谱构建引擎：
//   输入任意主题（如"小学数学3年级"），自动规划子主题 -> 多源抓取 -> 知识点入库。
//
// 实体（节点标签）：
//   Person  人物：有生卒年/职业/性别（人物接入点）
//   Event   事件：有发生时间/地点/类型（科举/贬谪/战争/著作…）
//   Topic   知识主题：任意学科/课程/概念（数学/分数/长方形/李白…）
//           entityKind 区分：subject(学科) / unit(单元) / concept(概念)
//
// 关系（RELATES.type 受控词表，按域分组）：
//   人—人：亲属/婚姻/师承/社会
//   人—事件：参与类
//   知识—知识：结构类（包含/前置/属于/应用/相关）
//   人/事件—知识：跨域关联类（归属领域）
// ============================================================

