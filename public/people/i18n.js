export function t(key, vars) {
  const table = isEn() ? EN : ZH
  let text = table[key] ?? ZH[key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll('{{' + name + '}}', String(value ?? ''))
    }
  }
  return text
}

export function switchPeopleLocale(next) {
  localStorage.setItem(STORAGE_KEY, next)
  const target = next === 'en' ? '/en/people/' : '/people/'
  location.assign(target + location.search + location.hash)
}

export function applyChrome() {
  document.documentElement.lang = isEn() ? 'en' : 'zh-CN'
  if (isEn()) document.title = 'Infiniti · Explore'
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n')
    if (el.getAttribute('data-i18n-html') === '1') el.innerHTML = t(key)
    else el.textContent = t(key)
  })
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.getAttribute('data-i18n-title'))
  })
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.placeholder = t(el.getAttribute('data-i18n-ph'))
  })
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')))
  })
  const home = document.getElementById('homeLink')
  if (home) home.href = isEn() ? '/en/' : '/'
  const loc = document.getElementById('localeBtn')
  if (loc && !loc.dataset.bound) {
    loc.dataset.bound = '1'
    loc.innerHTML = isEn()
      ? '<span>中</span> / <span class="on">EN</span>'
      : '<span class="on">中</span> / <span>EN</span>'
    loc.onclick = () => switchPeopleLocale(isEn() ? 'zh-CN' : 'en')
  }
}
